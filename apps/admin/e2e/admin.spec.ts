test("sales adds, reorders and deletes property photos", async ({ page }) => {
  await signIn(page, "sales");
  await page.goto("/properties");
  await page.getByRole("button", { name: "E2E Photo House" }).click();
  const png = (color: string) =>
    Buffer.from(
      `<svg xmlns="http://www.w3.org/2000/svg" width="40" height="30"><rect width="40" height="30" fill="${color}"/></svg>`
    );
  // Real PNGs are generated by drawing SVGs in the page, so no binary fixtures are needed.
  const files = await page.evaluate(
    async (svgs: string[]) => {
      const out: Array<{ name: string; data: number[] }> = [];
      for (const [i, svg] of svgs.entries()) {
        const img = new Image();
        img.src = `data:image/svg+xml;base64,${btoa(svg)}`;
        await img.decode();
        const c = document.createElement("canvas");
        c.width = 400;
        c.height = 300;
        c.getContext("2d")!.drawImage(img, 0, 0, 400, 300);
        const blob = await new Promise<Blob>((r) => c.toBlob((b) => r(b!), "image/png"));
        out.push({ name: `photo-${i}.png`, data: [...new Uint8Array(await blob.arrayBuffer())] });
      }
      return out;
    },
    [png("#0f2440").toString(), png("#f26b1d").toString()]
  );
  await page
    .locator('input[type="file"][accept^="image"]')
    .setInputFiles(
      files.map((f) => ({ name: f.name, mimeType: "image/png", buffer: Buffer.from(f.data) }))
    );
  const photos = page.getByRole("img", { name: /^Photo \d$/ });
  await expect(photos).toHaveCount(2);
  await expect(page.getByText("Cover", { exact: true })).toBeVisible();
  const first = await photos.nth(0).getAttribute("src");
  const second = await photos.nth(1).getAttribute("src");
  expect(first).toContain("/storage/v1/object/public/property-photos/");
  const res = await page.request.get(first!);
  expect(res.ok()).toBe(true);
  expect(res.headers()["content-type"]).toBe("image/jpeg");

  await page.getByRole("button", { name: "Move later" }).first().click();
  await expect(photos.nth(0)).toHaveAttribute("src", second!);

  page.once("dialog", (d) => d.accept());
  await page.getByRole("button", { name: "Delete photo" }).first().click();
  await expect(photos).toHaveCount(1);

  await page.keyboard.press("Escape");
  await page.reload();
  await expect(page.getByText("1 photo")).toBeVisible();
  expect((await page.request.get(second!)).status()).toBeGreaterThanOrEqual(400);
});
